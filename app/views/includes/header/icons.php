if (!function_exists('headerIconFor')) {
  /** Icon name for a CMS page, matched by slug or name. */
  function headerIconFor(string $key, bool $isParent = false): string {
    static $map = [
      'services' => 'grid', 'travel-services' => 'grid',
      'company' => 'building', 'about' => 'info', 'about-us' => 'info',
      'blogs' => 'article', 'blog' => 'article', 'news' => 'article',
      'contact' => 'phone', 'contact-us' => 'phone',
      'support' => 'headset', 'help' => 'headset', 'faq' => 'info',
    ];
    return $map[strtolower(trim($key))] ?? ($isParent ? 'folder' : 'file');
  }
